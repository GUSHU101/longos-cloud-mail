import {readFileSync} from 'node:fs';
import {isIP} from 'node:net';
import {domainToASCII} from 'node:url';

const manifest = JSON.parse(readFileSync(
  new URL('../mail-relay/remote-node-profile.json', import.meta.url),
  'utf8',
));

export const remoteMailNodeManifest = Object.freeze(manifest);

export function parseRemoteMailNodeEnv(source) {
  const values = {};
  String(source).split(/\r?\n/).forEach((rawLine, index) => {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) return;
    const match = /^(?:export\s+)?([A-Z][A-Z0-9_]*)=(.*)$/.exec(line);
    if (!match) throw new Error(`Line ${index + 1} is not a KEY=value assignment.`);
    const [, name, rawValue] = match;
    if (Object.hasOwn(values, name)) throw new Error(`${name} is defined more than once.`);
    if (/['"`]/.test(rawValue) || /[\r\n\0]/.test(rawValue)) {
      throw new Error(`${name} must use the plain value format generated by LONGOS.`);
    }
    values[name] = rawValue.trim();
  });

  return values;
}

export function validateRemoteMailNodePublicProfile(sourceOrValues) {
  const supplied = typeof sourceOrValues === 'string'
    ? parseRemoteMailNodeEnv(sourceOrValues)
    : {...sourceOrValues};
  const values = {...manifest.publicDefaults, ...supplied};
  const errors = [];

  if (!Object.hasOwn(supplied, 'MAIL_NODE_PROFILE_VERSION')) {
    errors.push('MAIL_NODE_PROFILE_VERSION is missing. Download a fresh profile from LONGOS.');
  } else if (values.MAIL_NODE_PROFILE_VERSION !== manifest.version) {
    errors.push(`MAIL_NODE_PROFILE_VERSION must be ${manifest.version}.`);
  }

  for (const name of manifest.identityVariables) {
    if (!String(values[name] || '').trim()) errors.push(`${name} is required.`);
  }
  for (const name of manifest.secretVariables) {
    if (String(supplied[name] || '').trim()) {
      errors.push(`${name} must stay out of the public profile and be entered as a Coolify Secret.`);
    }
  }

  const hostname = normalizeDomain(values.MAIL_HOSTNAME);
  if (!hostname) errors.push('MAIL_HOSTNAME must be a valid DNS hostname.');

  const ips = csv(values.MAIL_PUBLIC_IPS);
  if (ips.length === 0 || ips.some(value => isIP(value) === 0) || new Set(ips).size !== ips.length) {
    errors.push('MAIL_PUBLIC_IPS must contain one or more unique IP addresses.');
  }

  const domains = csv(values.MAIL_DOMAINS).map(normalizeDomain);
  const allowedDomains = csv(values.ALLOWED_SENDER_DOMAINS).map(normalizeDomain);
  if (domains.length === 0 || domains.some(value => !value) || new Set(domains).size !== domains.length) {
    errors.push('MAIL_DOMAINS must contain unique DNS domains.');
  }
  if (allowedDomains.length === 0 || allowedDomains.some(value => !value)
    || allowedDomains.some(value => !domains.includes(value))) {
    errors.push('ALLOWED_SENDER_DOMAINS must be a non-empty subset of MAIL_DOMAINS.');
  }

  if (!/^[a-z0-9][a-z0-9_-]{0,62}$/.test(String(values.DKIM_SELECTOR || '').toLowerCase())) {
    errors.push('DKIM_SELECTOR is invalid.');
  }
  if (!['ipv4', 'ipv6', 'all'].includes(values.INET_PROTOCOLS)) {
    errors.push('INET_PROTOCOLS must be ipv4, ipv6, or all.');
  }

  const relayPort = integer(values.RELAY_HTTP_PORT, 1024, 65535);
  if (relayPort === null) errors.push('RELAY_HTTP_PORT must be between 1024 and 65535.');
  if (!/^[a-z0-9][a-z0-9-]{0,62}$/.test(values.MAIL_NODE_VOLUME_PREFIX || '')) {
    errors.push('MAIL_NODE_VOLUME_PREFIX is invalid.');
  }
  if (!['auto', 'quic', 'http2'].includes(values.TUNNEL_PROTOCOL)) {
    errors.push('TUNNEL_PROTOCOL must be auto, quic, or http2.');
  }
  if (!['debug', 'info', 'warn', 'error', 'fatal'].includes(values.TUNNEL_LOG_LEVEL)) {
    errors.push('TUNNEL_LOG_LEVEL is invalid.');
  }

  const metrics = /^127\.0\.0\.1:(\d{4,5})$/.exec(values.TUNNEL_METRICS_ADDRESS || '');
  const metricsPort = metrics ? integer(metrics[1], 1024, 65535) : null;
  if (metricsPort === null || metricsPort === relayPort) {
    errors.push('TUNNEL_METRICS_ADDRESS must use a distinct 127.0.0.1 port between 1024 and 65535.');
  }
  if (!/^cloudflare\/cloudflared:[0-9][a-z0-9._-]{0,63}$/.test(values.CLOUDFLARED_IMAGE || '')) {
    errors.push('CLOUDFLARED_IMAGE must pin an official explicit version.');
  }

  for (const [reservation, limit, label] of [
    ['RELAY_MEMORY_RESERVATION', 'RELAY_MEMORY_LIMIT', 'Relay'],
    ['TUNNEL_MEMORY_RESERVATION', 'TUNNEL_MEMORY_LIMIT', 'Tunnel'],
  ]) {
    const reservedBytes = memoryBytes(values[reservation]);
    const limitBytes = memoryBytes(values[limit]);
    if (reservedBytes === null || limitBytes === null) {
      errors.push(`${label} memory values must use forms such as 256m or 1g.`);
    } else if (reservedBytes > limitBytes) {
      errors.push(`${label} memory reservation cannot exceed its limit.`);
    }
  }
  for (const name of ['RELAY_PIDS_LIMIT', 'TUNNEL_PIDS_LIMIT']) {
    if (integer(values[name], 32, 4096) === null) errors.push(`${name} must be between 32 and 4096.`);
  }

  if (errors.length) {
    throw new Error(`Invalid remote mail node profile:\n- ${errors.join('\n- ')}`);
  }

  const normalized = {
    ...values,
    MAIL_HOSTNAME: hostname,
    MAIL_PUBLIC_IPS: ips.join(','),
    MAIL_DOMAINS: domains.join(','),
    ALLOWED_SENDER_DOMAINS: allowedDomains.join(','),
    DKIM_SELECTOR: values.DKIM_SELECTOR.toLowerCase(),
  };
  manifest.secretVariables.forEach(name => delete normalized[name]);

  return Object.freeze(normalized);
}

function csv(value) {
  return String(value || '').split(',').map(item => item.trim().toLowerCase()).filter(Boolean);
}

function normalizeDomain(value) {
  const domain = domainToASCII(String(value || '').trim().toLowerCase().replace(/\.$/, ''));
  const labels = domain.split('.');
  return domain.length <= 253 && labels.length >= 2
    && labels.every(label => /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/.test(label))
    ? domain
    : '';
}

function integer(value, minimum, maximum) {
  if (!/^[0-9]+$/.test(String(value || ''))) return null;
  const parsed = Number(value);
  return Number.isSafeInteger(parsed) && parsed >= minimum && parsed <= maximum ? parsed : null;
}

function memoryBytes(value) {
  const match = /^([1-9][0-9]{0,5})([kmg])$/.exec(String(value || '').toLowerCase());
  if (!match) return null;
  return Number(match[1]) * ({k: 1024, m: 1024 ** 2, g: 1024 ** 3})[match[2]];
}
